import { test, expect } from '@playwright/test'
test('desde móvil: crear, personalizar, caminar, interactuar y recargar', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/emiverse/')
  await expect(page.getByText('EmiVerse — Created by Emily', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Crear personaje', exact: true }).click()
  await page.getByLabel('¿Cómo te llamas?').fill('Luna')
  await page.getByRole('button', { name: 'Piel 3', exact: true }).click()
  await page.getByRole('button', { name: 'Ropa 4', exact: true }).click()
  await page.getByRole('button', { name: 'Melena', exact: true }).click()
  await page.getByRole('button', { name: '¡A vivir aventuras!' }).click()
  await expect(page.locator('.player-name')).toHaveText('Luna')
  const startX = Number(await page.locator('.world-player').getAttribute('data-x'))
  const right = page.getByRole('button', { name: 'Mover derecha', exact: true })
  const rect = await right.boundingBox()
  await page.mouse.move(rect!.x + rect!.width / 2, rect!.y + rect!.height / 2)
  await page.mouse.down()
  await expect.poll(async () => Number(await page.locator('.world-player').getAttribute('data-x'))).toBeGreaterThan(startX + 2)
  await page.mouse.up()
  await page.getByRole('button', { name: 'Interactuar con Nubi' }).click()
  await page.getByRole('button', { name: 'Darle un bocadito' }).click()
  await expect(page.locator('.memory-count')).toContainText('1')
  await page.getByRole('button', { name: 'Jardín', exact: true }).click()
  await page.getByRole('button', { name: 'Interactuar con Arcoflor' }).click()
  await page.getByRole('button', { name: 'Regar con cariño' }).click()
  await page.getByRole('button', { name: 'Interactuar con Pintar' }).click()
  await page.getByRole('button', { name: 'Pintar mi obra' }).click()
  await page.getByRole('button', { name: 'Casita', exact: true }).click()
  await page.getByRole('button', { name: 'Interactuar con Sorpresa' }).click()
  await page.getByRole('button', { name: 'Abrir mi sorpresa' }).click()
  await page.getByRole('button', { name: 'Mi vestidor', exact: true }).click()
  await page.getByRole('button', { name: 'Corona', exact: true }).click()
  await page.getByRole('button', { name: '¡A vivir aventuras!' }).click()
  await page.getByRole('button', { name: 'Interactuar con Música' }).click()
  await page.getByRole('button', { name: '¡Que suene la música!' }).click()
  await expect(page.locator('.memory-count')).toContainText('5')
  await page.reload()
  await expect(page.locator('.player-name')).toHaveText('Luna')
  await expect(page.locator('.memory-count')).toContainText('5')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/emiverse-world-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.screenshot({ path: '/tmp/emiverse-world-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Cómo jugar', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(errors).toEqual([])
})
test('mover tocando el suelo y guardar personajes de forma independiente', async ({ page }) => {
  await page.goto('/emiverse/')
  const scene = page.getByRole('region', { name: 'Escenario de la casita' })
  const r = await scene.boundingBox()
  await scene.click({ position: { x: r!.width * .13, y: r!.height * .85 } })
  await expect.poll(async () => Number(await page.locator('.world-player').getAttribute('data-x'))).toBeLessThan(45)
  await page.getByRole('button', { name: 'Mover arriba' }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Cómo jugar', exact: true }).click()
  const atPause = await page.locator('.world-player').getAttribute('data-x')
  await expect(page.locator('.world-player')).toHaveAttribute('data-x', atPause!)
  await page.keyboard.press('Escape')
})
